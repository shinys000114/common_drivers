static const u8 jpeg_components[] = {
	3, 0, 0x22, 0, 1, 0x11, 1, 2, 0x11, 1,
};

static const u8 jpeg_sos[] = {
	0xff, 0xda, 0, 12, 3, 0, 0, 1, 0x11, 2, 0x11, 0, 63, 0,
};

static void jpeg_put_word(u8 **cursor, u16 word)
{
	*(*cursor)++ = word >> 8;
	*(*cursor)++ = word;
}

int s7d_jpeg_build_header(u32 input_format, u32 width, u32 height,
			  const struct s7d_jpeg_quantization *quant,
			  struct s7d_jpeg_header *header)
{
	struct s7d_jpeg_header result;
	u8 *cursor = result.data;
	unsigned int table, i;

	static_assert(S7D_JPEG_HEADER_BYTES ==
		2 + 4 + 2 * (1 + S7D_JPEG_QUANT_COEFFICIENTS) +
		4 + 2 * (1 + sizeof(jpeg_huffman_dc[0])) +
		2 * (1 + sizeof(jpeg_huffman_ac[0])) +
		9 + sizeof(jpeg_components) + 3 + sizeof(jpeg_sos));
	if (!header || !quant)
		return -EINVAL;
	if (input_format != V4L2_PIX_FMT_NV12 && input_format != V4L2_PIX_FMT_NV21)
		return -EOPNOTSUPP;
	if (!width || !height || width > U16_MAX || height > U16_MAX)
		return -ERANGE;
	for (table = 0; table < S7D_JPEG_QUANT_TABLES; table++)
		for (i = 0; i < S7D_JPEG_QUANT_COEFFICIENTS; i++)
			if (!quant->dqt[table][i])
				return -EINVAL;

	jpeg_put_word(&cursor, 0xffd8);
	jpeg_put_word(&cursor, 0xffdb);
	jpeg_put_word(&cursor, 2 + 2 * (1 + S7D_JPEG_QUANT_COEFFICIENTS));
	for (table = 0; table < S7D_JPEG_QUANT_TABLES; table++) {
		*cursor++ = table;
		memcpy(cursor, quant->dqt[table], sizeof(quant->dqt[table]));
		cursor += sizeof(quant->dqt[table]);
	}
	jpeg_put_word(&cursor, 0xffc4);
	jpeg_put_word(&cursor, 2 + 2 * (1 + sizeof(jpeg_huffman_dc[0])) +
		      2 * (1 + sizeof(jpeg_huffman_ac[0])));
	for (table = 0; table < 2; table++) {
		*cursor++ = table;
		memcpy(cursor, jpeg_huffman_dc[table], sizeof(jpeg_huffman_dc[table]));
		cursor += sizeof(jpeg_huffman_dc[table]);
	}
	for (table = 0; table < 2; table++) {
		*cursor++ = 0x10 | table;
		memcpy(cursor, jpeg_huffman_ac[table], sizeof(jpeg_huffman_ac[table]));
		cursor += sizeof(jpeg_huffman_ac[table]);
	}
	jpeg_put_word(&cursor, 0xffc0);
	jpeg_put_word(&cursor, 17);
	*cursor++ = 8;
	jpeg_put_word(&cursor, height);
	jpeg_put_word(&cursor, width);
	memcpy(cursor, jpeg_components, sizeof(jpeg_components));
	cursor += sizeof(jpeg_components);
	for (i = 0; i < 3; i++)
		*cursor++ = 0xff;
	memcpy(cursor, jpeg_sos, sizeof(jpeg_sos));
	*header = result;
	return 0;
}

int s7d_jpeg_validate_output(const u8 *scan, size_t scan_capacity,
			     u32 produced_bytes, size_t capture_capacity,
			     struct s7d_jpeg_output *output)
{
	struct s7d_jpeg_output result = { .scan_bytes = produced_bytes };
	bool entropy = false;
	size_t i = 0;

	if (!scan || !output)
		return -EINVAL;
	if (produced_bytes > scan_capacity)
		return -EOVERFLOW;
	if (produced_bytes < 3)
		return -EBADMSG;
	if (check_add_overflow((u32)S7D_JPEG_HEADER_BYTES,
			       produced_bytes, &result.bytesused))
		return -EOVERFLOW;
	if (result.bytesused > capture_capacity)
		return -ENOSPC;
	while (i < produced_bytes) {
		if (scan[i++] != 0xff) {
			entropy = true;
			continue;
		}
		if (i == produced_bytes)
			return -EBADMSG;
		if (!scan[i]) {
			i++;
			entropy = true;
			continue;
		}
		while (scan[i] == 0xff)
			if (++i == produced_bytes)
				return -EBADMSG;
		if (scan[i] != 0xd9 || i != produced_bytes - 1 || !entropy)
			return -EBADMSG;
		*output = result;
		return 0;
	}
	return -EBADMSG;
}
